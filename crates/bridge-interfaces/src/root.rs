//! Restricted root ingress for Agent Bridge orchestrators.
//!
//! The orchestrator-facing surface: a local Unix-stream socket speaking one
//! JSON object per line (ndjson), serving exactly three operations —
//! `me`, `send` and `status` — behind per-caller root grants. There is
//! deliberately no fourth operation: no retry, no reset, no enumeration, no
//! publisher or admin passthrough, and no receipt-token capability in this
//! build (that stays unimplemented until a real producer predeclares a
//! matching receipt tier).
//!
//! Isolation model:
//! - Root tokens are valid only on this socket. They are a separate grant
//!   list from the core publisher/admin grants, so a root credential can
//!   never authorize publisher or admin ingress, and a publisher token can
//!   never reach a root operation.
//! - A request never asserts an identity. The acting caller is the grant's
//!   attested caller, configured out-of-band by the operator; the grant
//!   anchor is a substitute until the adapter Module's protected native
//!   attestation provider lands, and this surface is documented as
//!   unqualified for real native actor proof until then.
//! - Root `send` always publishes with `keep_all` to an exact grant-listed
//!   recipient; coalescing controls (`latest`/`batch`) are not even part of
//!   the request schema.
//! - Custody event ids are namespaced per caller so two callers choosing the
//!   same `request_id` can never collide, conflict or observe each other's
//!   events.
//!
//! Status answers distinguish durable custody from native evidence tiers.
//! This build reports every native tier as `not_available` rather than
//! guessing: the core protocol currently carries custody receipts only.

