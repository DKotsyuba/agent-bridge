/// Default operational body bound for root sends, in bytes of UTF-8.
///
/// Configurable through [`RootConfig::max_body_bytes`]; there is no
/// owner-mandated fixed cap, only an explicit refusal when exceeded.
pub const DEFAULT_MAX_BODY_BYTES: usize = 16 * 1024;

/// Maximum accepted request line length in bytes.
///
/// Larger lines are refused before parsing; root requests carry bounded
/// bodies by contract, so this is a backstop, not a working limit.
const MAX_REQUEST_BYTES: usize = 256 * 1024;

/// Longest caller-supplied `request_id` accepted, in bytes.
///
/// The custody event id adds a fixed 18-byte caller namespace prefix and the
/// core bound is 256 bytes, so request ids are capped well below it.
const MAX_REQUEST_ID_BYTES: usize = 200;

/// Length of the hexadecimal caller namespace prefix in custody event ids.
const CALLER_PREFIX_BYTES: usize = 18;

/// Configuration for the restricted root ingress, usually loaded from TOML.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RootConfig {
    /// Filesystem path of this ingress's Unix stream socket.
    ///
    /// Must differ from the core publisher socket; the two surfaces share
    /// nothing.
    pub socket: PathBuf,
    /// Core publisher daemon socket that custody publishes are forwarded to.
    pub custody_socket: PathBuf,
    /// Publisher-grant token used for custody forwarding.
    ///
    /// A dedicated grant configured on the core daemon for this ingress
    /// (publisher stamp and allowlists held there). It is never accepted by
    /// this ingress and never disclosed to root callers.
    pub custody_token: String,
    /// Operational body bound for `send`, in bytes of UTF-8.
    ///
    /// Oversize bodies are refused with an explicit `invalid` error; they
    /// are never truncated.
    #[serde(default = "default_max_body_bytes")]
    pub max_body_bytes: usize,
    /// Root caller grants; at least one is required to serve anything.
    #[serde(default)]
    pub grants: Vec<RootGrant>,
}

/// Returns [`DEFAULT_MAX_BODY_BYTES`] for serde defaults.
const fn default_max_body_bytes() -> usize {
    DEFAULT_MAX_BODY_BYTES
}

/// One root caller grant.
///
/// Binds a secret token to exactly one attested caller and to the exact
/// recipients, kinds and delivery modes that caller may use. The token plus
/// socket access is the caller's authentication; the attested caller is
/// operator-configured out-of-band and is never taken from a request.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RootGrant {
    /// Secret bearer token (unguessable, generated by the operator).
    pub token: String,
    /// The attested native caller this grant represents.
    pub caller: AttestedCaller,
    /// Exact canonical recipient addresses this caller may send to.
    pub recipients: Vec<String>,
    /// Event kinds this caller may send.
    pub kinds: Vec<String>,
    /// Requested delivery modes this caller may use.
    pub modes: Vec<String>,
}

impl RootGrant {
    /// Validates everything the runtime will check against.
    ///
    /// The attested caller address, every recipient canonical address, kind
    /// and mode must be well-formed at load time so authorization decisions
    /// never run on malformed allowlist entries. Returns a human-named
    /// error string on the first problem; nothing is served from a config
    /// that fails this check.
    pub fn validate(&self) -> Result<(), String> {
        self.caller.validate()?;
        for recipient in &self.recipients {
            NativeAddress::parse(recipient).map_err(|error| format!("recipient: {error}"))?;
        }
        for kind in &self.kinds {
            Kind::new(kind.clone())
                .map_err(|error| format!("kind: {error}"))?;
        }
        for mode in &self.modes {
            Mode::parse(mode).map_err(|error| format!("mode: {error}"))?;
        }
        Ok(())
    }
}

/// An attested native caller identity.
///
/// Produced by the adapter Module's protected native correlation in
/// production. Until that provider lands, the only constructor used is the
/// operator-configured anchor ([`AttestedCaller::configured`]), which is a
/// fixture-grade substitute: it binds the configured address but proves
/// nothing about the live native actor. `source` records which facility
/// produced the attestation so every disclosure can stay truthful about
/// its strength.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AttestedCaller {
    /// Exact native logical address of the caller.
    pub address: NativeAddress,
    /// Whether the caller is the root session or a child actor.
    pub actor: CallerActor,
    /// Fenced endpoint epoch of the caller's transport binding.
    pub endpoint_epoch: u64,
    /// Wall clock when the attestation evidence was observed, Unix epoch
    /// milliseconds.
    pub attested_at_ms: u64,
    /// Facility that produced this attestation, for truthful disclosure.
    ///
    /// `operator-config` marks the substitute anchor; the adapter provider
    /// carries its own reference once integrated.
    pub source: String,
}

/// Whether an attested caller is a native root session or a child actor.
///
/// Children may hold their own grants for their own traffic but may never
/// drain, acknowledge or observe root data; that separation is enforced by
/// the per-caller grant binding, not by this label alone.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CallerActor {
    /// The native root session itself.
    Root,
    /// A child actor with its own attested address.
    Child,
}

impl CallerActor {
    /// Wire name of this actor kind.
    pub const fn as_str(self) -> &'static str {
        match self {
            CallerActor::Root => "root",
            CallerActor::Child => "child",
        }
    }
}

impl AttestedCaller {
    /// Builds the operator-configured substitute anchor.
    ///
    /// Fixture-grade: suitable for isolated qualification only. `source` is
    /// set to `operator-config` so `me` responses and logs always show that
    /// this identity came from configuration, not native proof.
    pub fn configured(
        address: NativeAddress,
        actor: CallerActor,
        endpoint_epoch: u64,
        attested_at_ms: u64,
    ) -> Self {
        AttestedCaller {
            address,
            actor,
            endpoint_epoch,
            attested_at_ms,
            source: "operator-config".to_string(),
        }
    }

    /// Validates the attested caller's own fields.
    ///
    /// The address must satisfy the canonical address rules and the source
    /// must be a non-empty bounded label; errors name the field.
    pub fn validate(&self) -> Result<(), String> {
        self.address
            .validate()
            .map_err(|error| format!("caller address: {error}"))?;
        if self.source.is_empty() || self.source.len() > 128 {
            return Err("caller attestation source must be 1..=128 bytes".to_string());
        }
        Ok(())
    }

    /// Stable per-caller namespace prefix for custody event ids.
    ///
    /// First 16 hex characters (64 bits) of SHA-256 over the canonical
    /// address text, prefixed with `r`. Two callers therefore never share a
    /// custody namespace even when they choose identical request ids.
    pub fn namespace(&self) -> String {
        let digest = Sha256::digest(self.address.to_canonical_string().as_bytes());
        format!("r{}", &hex_prefix(&digest, 16))
    }
}

/// Lowercase-hex encodes the first `characters` hex digits of a digest.
fn hex_prefix(digest: &[u8], characters: usize) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    digest
        .iter()
        .flat_map(|byte| [(byte >> 4) as usize, (byte & 0x0f) as usize])
        .map(|nibble| HEX[nibble] as char)
        .take(characters)
        .collect()
}

/// Wire form of a `me` request after closed-key validation.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct MeWire {
    /// Must be exactly `"me"`; checked by the dispatcher before parsing.
    #[allow(dead_code)]
    op: String,
    /// Root grant bearer token.
    token: String,
}

/// Wire form of a `send` request after closed-key validation.
///
/// There is intentionally no `policy`, no `metadata`, no `expires_at`, no
/// `source`/`caller` field and no token-tier field: the schema itself
/// keeps root sends on `keep_all` semantics and caller identity out of
/// requests.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct SendWire {
    /// Must be exactly `"send"`; checked by the dispatcher before parsing.
    #[allow(dead_code)]
    op: String,
    /// Root grant bearer token.
    token: String,
    /// Caller-chosen request id, namespaced into the custody event id.
    request_id: String,
    /// Exact canonical recipient address text.
    recipient: String,
    /// Event kind (must be in the grant's allowlist).
    kind: String,
    /// Requested delivery mode name.
    mode: String,
    /// Notification body text.
    body: String,
}

/// Wire form of a `status` request after closed-key validation.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct StatusWire {
    /// Must be exactly `"status"`; checked by the dispatcher before parsing.
    #[allow(dead_code)]
    op: String,
    /// Root grant bearer token.
    token: String,
    /// The caller's own request id.
    request_id: String,
}

/// Typed `send` arguments for in-process callers (the MCP wrapper).
///
/// Same fields and rules as the wire form minus the token, which the MCP
/// transport supplies from its own protected environment.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SendArgs {
    /// Caller-chosen request id.
    pub request_id: String,
    /// Exact canonical recipient address text.
    pub recipient: String,
    /// Event kind.
    pub kind: String,
    /// Requested delivery mode name.
    pub mode: String,
    /// Notification body text.
    pub body: String,
}

/// One response line from the root ingress.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum RootResponse {
    /// Answer to `me`: the attested caller and its permitted capabilities.
    Me {
        /// The grant's attested caller disclosure.
        caller: CallerInfo,
    },
    /// Custody accepted (freshly or as an identical replay) for a `send`.
    Sent {
        /// The caller's original request id.
        request_id: String,
        /// Durable custody receipt from the core (event id is namespaced).
        receipt: CustodyReceipt,
    },
    /// Answer to `status`: only this caller's own request, with every
    /// evidence tier named separately.
    Status {
        /// The caller's original request id.
        request_id: String,
        /// Durable custody receipt, or `None` when never accepted.
        custody: Option<CustodyReceipt>,
        /// Native queue/inbox acceptance evidence tier.
        native_acceptance: Availability,
        /// Model-context observation evidence tier.
        context_observed: Availability,
        /// Uncertainty/reconciliation state tier.
        uncertainty: Availability,
    },
    /// Structured refusal; nothing was accepted or disclosed.
    Error {
        /// Machine-readable class: auth, forbidden, unsupported, invalid,
        /// conflict, capacity or internal.
        class: String,
        /// Human-readable detail without secrets.
        detail: String,
    },
}

/// Availability of one evidence tier in a status answer.
///
/// Only [`Availability::NotAvailable`] is produced by this build: the core
/// protocol currently carries custody receipts, so every native tier is
/// reported as explicitly unsupported rather than guessed. When the core
/// adds those tiers, this enum grows an `Available` carrier without
/// changing the response shape.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Availability {
    /// The tier is not provided by the backing protocol in this build.
    NotAvailable,
}

/// The `me` disclosure: attested identity plus permitted capabilities.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CallerInfo {
    /// Canonical text form of the attested caller address.
    pub address: String,
    /// `root` or `child`, from the attestation.
    pub actor: String,
    /// Fenced endpoint epoch from the attestation.
    pub endpoint_epoch: u64,
    /// Facility that produced the attestation (truthful strength marker).
    pub attestation_source: String,
    /// Delivery modes this caller may request.
    pub modes: Vec<String>,
    /// Exact canonical recipients this caller may send to.
    pub recipients: Vec<String>,
    /// Event kinds this caller may send.
    pub kinds: Vec<String>,
}

/// A running root ingress bound to its socket.
///
/// Dropping the handle does not stop the service; call [`RootRunning::shutdown`]
/// and [`RootRunning::join`] for a bounded, drained stop.
pub struct RootRunning {
    socket_path: PathBuf,
    state: Arc<RootState>,
    accept_thread: JoinHandle<()>,
}

/// Shared ingress state behind the accept loop.
struct RootState {
    config: RootConfig,
    running: AtomicBool,
    socket_path: PathBuf,
}

/// Starts the root ingress: validates grants, binds the socket and spawns
/// the accept loop.
///
/// Fails with a human-named error string when the configuration is invalid
/// or the socket cannot be bound — never serves with partial grant state.
/// A stale socket file at the configured path is removed first (it can only
/// belong to a dead ingress on this local path).
pub fn start(config: RootConfig) -> Result<RootRunning, String> {
    if config.grants.is_empty() {
        return Err("root ingress requires at least one grant".to_string());
    }
    for grant in &config.grants {
        grant.validate()?;
    }
    let _ = std::fs::remove_file(&config.socket);
    if let Some(parent) = config.socket.parent() {
        std::fs::create_dir_all(parent).map_err(|error| format!("socket directory: {error}"))?;
    }
    let listener =
        UnixListener::bind(&config.socket).map_err(|error| format!("bind socket: {error}"))?;
    listener
        .set_nonblocking(true)
        .map_err(|error| format!("socket non-blocking: {error}"))?;
    let state = Arc::new(RootState {
        config,
        running: AtomicBool::new(true),
        socket_path: config.socket.clone(),
    });
    bridge_core::service::log_event(
        "info",
        "root_ingress_starting",
        &[
            ("socket", &state.socket_path.display().to_string()),
            ("grants", &state.config.grants.len().to_string()),
        ],
    );
    let accept_state = Arc::clone(&state);
    let accept_thread = std::thread::Builder::new()
        .name("bridge-root-accept".into())
        .spawn(move || root_accept_loop(listener, accept_state))
        .map_err(|error| format!("spawn accept thread: {error}"))?;
    Ok(RootRunning {
        socket_path: config.socket,
        state,
        accept_thread,
    })
}

impl RootRunning {
    /// The bound socket path for clients.
    pub fn socket_path(&self) -> &std::path::Path {
        &self.socket_path
    }

    /// Requests a drained stop (idempotent).
    pub fn shutdown(&self) {
        self.state.running.store(false, Ordering::SeqCst);
    }

    /// Waits for the accept loop to finish; bounded by the caller.
    pub fn join(self) {
        let _ = self.accept_thread.join();
    }
}

/// Accept loop: non-blocking accept polled while running; each connection
/// is handled on its own thread so one caller cannot block others.
///
/// A drained stop closes the loop (within one poll interval) and removes
/// the socket file; in-flight requests finish on their own threads. Same
/// trade-off as the core publisher service: connection threads are not
/// joined so shutdown stays bounded.
fn root_accept_loop(listener: UnixListener, state: Arc<RootState>) {
    while state.running.load(Ordering::SeqCst) {
        match listener.accept() {
            Ok((stream, _)) => {
                let connection_state = Arc::clone(&state);
                let _ = std::thread::Builder::new()
                    .name("bridge-root-connection".into())
                    .spawn(move || handle_root_connection(stream, connection_state));
            }
            Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                std::thread::sleep(Duration::from_millis(20));
            }
            Err(error) => {
                bridge_core::service::log_event(
                    "error",
                    "root_accept_failed",
                    &[("error", &error.to_string())],
                );
            }
        }
    }
    let _ = std::fs::remove_file(&state.socket_path);
    bridge_core::service::log_event("info", "root_ingress_stopped", &[]);
}

/// Serves one connection: read lines, answer, until EOF or stop.
///
/// Each connection lazily opens one custody client to the core publisher
/// daemon and reuses it for the connection's lifetime.
fn handle_root_connection(stream: UnixStream, state: Arc<RootState>) {
    let _ = stream.set_nonblocking(false);
    let cloned = match stream.try_clone() {
        Ok(cloned) => cloned,
        Err(error) => {
            bridge_core::service::log_event(
                "error",
                "root_connection_clone_failed",
                &[("error", &error.to_string())],
            );
            return;
        }
    };
    let reader = BufReader::new(cloned);
    let mut writer = stream;
    // One custody connection for the whole request session, opened up
    // front; a failed connect answers per-request as an internal refusal
    // and never fabricates custody state.
    let mut custody = BridgeClient::connect(&state.config.custody_socket).ok();
    for line in reader.lines() {
        let line = match line {
            Ok(line) => line,
            Err(_) => break,
        };
        if line.len() > MAX_REQUEST_BYTES {
            let _ = write_root_response(
                &mut writer,
                &error_response("invalid", &format!("request exceeds {MAX_REQUEST_BYTES} bytes")),
            );
            continue;
        }
        let response = match parse_request(&line) {
            Ok(request) => serve(&state, request, custody.as_mut()),
            Err(response) => Err(response),
        };
        match response {
            Ok(response) => {
                if write_root_response(&mut writer, &response).is_err() {
                    break;
                }
            }
            Err(response) => {
                if write_root_response(&mut writer, &response).is_err() {
                    break;
                }
            }
        }
    }
}

/// One parsed, closed-schema-valid request.
pub(crate) enum RootRequest {
    /// `me`: disclose the attested caller.
    Me { token: String },
    /// `send`: publish one bounded notification under custody.
    Send { token: String, args: SendArgs },
    /// `status`: disclose only this caller's own request state.
    Status { token: String, request_id: String },
}

/// Parses and closed-key-validates one ndjson request line.
///
/// The schema is closed by exact key-set comparison per operation: unknown
/// operations, unknown keys and missing keys are all refused as
/// `unsupported`/`invalid` before any typed field is read. This is the
/// trust boundary for the request shape.
fn parse_request(line: &str) -> Result<RootRequest, RootResponse> {
    let value: serde_json::Value = match serde_json::from_str(line) {
        Ok(value) => value,
        Err(error) => {
            return Err(error_response(
                "unsupported",
                &format!("unparseable request: {error}"),
            ))
        }
    };
    let object = match value.as_object() {
        Some(object) => object,
        None => {
            return Err(error_response(
                "unsupported",
                "request must be a JSON object",
            ))
        }
    };
    let op = match object.get("op").and_then(|op| op.as_str()) {
        Some(op) => op,
        None => return Err(error_response("unsupported", "request must carry an op")),
    };
    let keys: Vec<&str> = object.keys().map(String::as_str).collect();
    let allowed: &[&str] = match op {
        "me" => &["op", "token"],
        "send" => &["op", "token", "request_id", "recipient", "kind", "mode", "body"],
        "status" => &["op", "token", "request_id"],
        other => {
            return Err(error_response(
                "unsupported",
                &format!("unknown op {other:?}: only me/send/status exist"),
            ))
        }
    };
    if keys.len() != allowed.len() || allowed.iter().any(|key| !object.contains_key(*key)) {
        return Err(error_response(
            "unsupported",
            &format!("closed schema: op {op:?} accepts exactly {allowed:?}"),
        ));
    }
    match op {
        "me" => {
            let wire: MeWire = serde_json::from_value(value)
                .map_err(|error| error_response("invalid", &format!("me request: {error}")))?;
            Ok(RootRequest::Me { token: wire.token })
        }
        "send" => {
            let wire: SendWire = serde_json::from_value(value)
                .map_err(|error| error_response("invalid", &format!("send request: {error}")))?;
            Ok(RootRequest::Send {
                token: wire.token,
                args: SendArgs {
                    request_id: wire.request_id,
                    recipient: wire.recipient,
                    kind: wire.kind,
                    mode: wire.mode,
                    body: wire.body,
                },
            })
        }
        "status" => {
            let wire: StatusWire = serde_json::from_value(value)
                .map_err(|error| error_response("invalid", &format!("status request: {error}")))?;
            Ok(RootRequest::Status {
                token: wire.token,
                request_id: wire.request_id,
            })
        }
        _ => unreachable!("op validated above"),
    }
}

/// Authenticates and serves one parsed request.
///
/// `custody` is the connection's lazily opened client to the core
/// publisher daemon; it is connected on first `send`/`status` and reused.
/// Refusals come back as the `Err` response variant.
pub(crate) fn serve(
    state: &RootState,
    request: RootRequest,
    custody: Option<&mut BridgeClient>,
) -> Result<RootResponse, RootResponse> {
    match request {
        RootRequest::Me { token } => serve_me(state, &token),
        RootRequest::Send { token, args } => serve_send(state, &token, args, custody),
        RootRequest::Status { token, request_id } => {
            serve_status(state, &token, &request_id, custody)
        }
    }
}

/// Serves the in-process request form used by the MCP wrapper.
///
/// Same rules as the socket path; the MCP layer supplies the token from
/// its protected environment rather than tool arguments.
pub(crate) fn serve_in_process(
    config: &RootConfig,
    request: RootRequest,
) -> Result<RootResponse, RootResponse> {
    let state = RootState {
        config: config.clone(),
        running: AtomicBool::new(true),
        socket_path: PathBuf::new(),
    };
    match bridge_client::BridgeClient::connect(&state.config.custody_socket) {
        Ok(mut custody) => serve(&state, request, Some(&mut custody)),
        Err(error) => Err(error_response(
            "internal",
            &format!("custody daemon unreachable: {error}"),
        )),
    }
}

/// Authenticates a token to its grant; the single entry gate for every
/// root operation, before validation, forwarding or any disclosure.
fn authenticate<'a>(state: &'a RootState, token: &str) -> Result<&'a RootGrant, RootResponse> {
    for grant in &state.config.grants {
        if constant_time_eq(token.as_bytes(), grant.token.as_bytes()) {
            return Ok(grant);
        }
    }
    bridge_core::service::log_event("warn", "root_auth_failed", &[]);
    Err(error_response("auth", "unknown or invalid root token"))
}

/// `me` flow: disclose only the grant's own attested caller and bounds.
fn serve_me(state: &RootState, token: &str) -> Result<RootResponse, RootResponse> {
    let grant = authenticate(state, token)?;
    Ok(RootResponse::Me {
        caller: CallerInfo {
            address: grant.caller.address.to_canonical_string(),
            actor: grant.caller.actor.as_str().to_string(),
            endpoint_epoch: grant.caller.endpoint_epoch,
            attestation_source: grant.caller.source.clone(),
            modes: grant.modes.clone(),
            recipients: grant.recipients.clone(),
            kinds: grant.kinds.clone(),
        },
    })
}

/// `send` flow: authenticate, authorize, validate, forward to custody.
///
/// Authorization is exact-string on the grant allowlists. The forwarded
/// body always carries `keep_all`; the caller namespace plus request id
/// become the custody event id, so per-caller replay/conflict semantics
/// come from the core unchanged. Nothing here can retry: a lost response
/// is the caller's to replay with the identical request.
fn serve_send(
    state: &RootState,
    token: &str,
    args: SendArgs,
    custody: Option<&mut BridgeClient>,
) -> Result<RootResponse, RootResponse> {
    let grant = authenticate(state, token)?;

    let recipient = NativeAddress::parse(&args.recipient)
        .map_err(|error| error_response("invalid", &format!("recipient: {error}")))?;
    let recipient_text = recipient.to_canonical_string();
    if !grant.recipients.contains(&recipient_text) {
        return Err(error_response(
            "forbidden",
            "grant does not allow this recipient",
        ));
    }
    let kind = Kind::new(args.kind.clone())
        .map_err(|error| error_response("invalid", &format!("kind: {error}")))?;
    if !grant.kinds.iter().any(|allowed| allowed == &args.kind) {
        return Err(error_response("forbidden", "grant does not allow this kind"));
    }
    let mode = Mode::parse(&args.mode)
        .map_err(|error| error_response("invalid", &format!("mode: {error}")))?;
    if !grant.modes.iter().any(|allowed| allowed == mode.as_str()) {
        return Err(error_response("forbidden", "grant does not allow this mode"));
    }
    if args.body.len() > state.config.max_body_bytes {
        return Err(error_response(
            "invalid",
            &format!("body exceeds {} bytes", state.config.max_body_bytes),
        ));
    }
    validate_request_id(&args.request_id)?;
    let event_id = namespaced_event_id(&grant.caller, &args.request_id)?;

    let client = custody_slot(state, custody)?;
    let body = PublishBody {
        event_id,
        recipient,
        kind,
        mode,
        policy: Policy::KeepAll,
        payload: args.body,
        metadata: Default::default(),
        expires_at: None,
    };
    match client.publish(&state.config.custody_token, &body) {
        Ok(receipt) => {
            bridge_core::service::log_event(
                "info",
                "root_send",
                &[
                    (
                        "caller",
                        &grant.caller.address.to_canonical_string(),
                    ),
                    ("request_id", &args.request_id),
                ],
            );
            Ok(RootResponse::Sent {
                request_id: args.request_id,
                receipt,
            })
        }
        Err(error) => Err(protocol_error_response(error)),
    }
}

/// `status` flow: only this caller's own namespaced request, with tiers.
fn serve_status(
    state: &RootState,
    token: &str,
    request_id: &str,
    custody: Option<&mut BridgeClient>,
) -> Result<RootResponse, RootResponse> {
    let grant = authenticate(state, token)?;
    validate_request_id(request_id)?;
    let event_id = namespaced_event_id(&grant.caller, request_id)?;
    let client = custody_slot(state, custody)?;
    match client.status(&state.config.custody_token, &event_id) {
        Ok(receipt) => Ok(RootResponse::Status {
            request_id: request_id.to_string(),
            custody: receipt,
            native_acceptance: Availability::NotAvailable,
            context_observed: Availability::NotAvailable,
            uncertainty: Availability::NotAvailable,
        }),
        Err(error) => Err(protocol_error_response(error)),
    }
}

/// Validates a caller-supplied request id.
///
/// Non-empty, at most [`MAX_REQUEST_ID_BYTES`] bytes, no control
/// characters; identical rules to a core event id so the namespaced
/// composition stays valid.
fn validate_request_id(request_id: &str) -> Result<(), RootResponse> {
    let invalid = |detail: &str| error_response("invalid", detail);
    if request_id.is_empty() {
        return Err(invalid("request_id must not be empty"));
    }
    if request_id.len() > MAX_REQUEST_ID_BYTES {
        return Err(invalid(&format!(
            "request_id exceeds {MAX_REQUEST_ID_BYTES} bytes"
        )));
    }
    if request_id.chars().any(char::is_control) {
        return Err(invalid("request_id must not contain control characters"));
    }
    Ok(())
}

/// Composes the per-caller namespaced custody event id.
fn namespaced_event_id(
    caller: &AttestedCaller,
    request_id: &str,
) -> Result<EventId, RootResponse> {
    let namespaced = format!("{}:{}", caller.namespace(), request_id);
    debug_assert!(namespaced.len() <= CALLER_PREFIX_BYTES + MAX_REQUEST_ID_BYTES);
    EventId::new(namespaced).map_err(|error| error_response("invalid", &error.to_string()))
}

/// Resolves the connection's custody client slot.
///
/// The connection handler opens the client up front; `None` here means the
/// core daemon was unreachable, which is answered as an explicit internal
/// refusal rather than a fabricated custody state.
fn custody_slot<'a>(
    state: &RootState,
    custody: Option<&'a mut BridgeClient>,
) -> Result<&'a mut BridgeClient, RootResponse> {
    if let Some(client) = custody {
        return Ok(client);
    }
    Err(error_response(
        "internal",
        &format!(
            "custody daemon connection not established for {}",
            state.config.custody_socket.display()
        ),
    ))
}

/// Maps a client protocol refusal to a root response.
fn protocol_error_response(error: bridge_client::ProtocolError) -> RootResponse {
    error_response(&error.class, &error.detail)
}

/// Builds the `Err` wire refusal.
pub(crate) fn error_response(class: &str, detail: &str) -> RootResponse {
    RootResponse::Error {
        class: class.to_string(),
        detail: detail.to_string(),
    }
}

/// Writes one ndjson response line.
fn write_root_response(
    stream: &mut UnixStream,
    response: &RootResponse,
) -> std::io::Result<()> {
    let mut line = serde_json::to_vec(response).map_err(std::io::Error::other)?;
    line.push(b'\n');
    stream.write_all(&line)?;
    stream.flush()
}

/// Constant-time byte-slice equality for token comparison.
///
/// Compares every byte of both slices regardless of where they differ, so
/// timing does not leak how much of a token matched.
fn constant_time_eq(left: &[u8], right: &[u8]) -> bool {
    if left.len() != right.len() {
        return false;
    }
    let mut difference: u8 = 0;
    for (l, r) in left.iter().zip(right) {
        difference |= l ^ r;
    }
    difference == 0
}

/// A minimal typed client for the root ingress socket.
///
/// One connection, sequential requests; used by the product CLI and tests.
#[derive(Debug)]
pub struct RootClient {
    stream: UnixStream,
    reader: BufReader<UnixStream>,
}

impl RootClient {
    /// Connects to the root ingress socket.
    ///
    /// Fails with the underlying I/O error when no ingress is listening.
    pub fn connect(socket: impl AsRef<std::path::Path>) -> std::io::Result<Self> {
        let stream = UnixStream::connect(socket)?;
        let reader = BufReader::new(stream.try_clone()?);
        Ok(RootClient { stream, reader })
    }

    /// Performs one raw round trip with a request line already serialized.
    ///
    /// Exposed for tests that must speak below the typed helpers (closed
    /// schema probes, forged requests).
    pub fn raw(&mut self, request_json: &str) -> std::io::Result<RootResponse> {
        self.stream.write_all(request_json.as_bytes())?;
        self.stream.write_all(b"\n")?;
        self.stream.flush()?;
        let mut line = String::new();
        self.reader.read_line(&mut line)?;
        serde_json::from_str(&line)
            .map_err(|error| std::io::Error::other(format!("unparseable response: {error}")))
    }

    /// Calls `me` for the given token.
    pub fn me(&mut self, token: &str) -> std::io::Result<RootResponse> {
        self.raw(&format!(r#"{{"op":"me","token":"{token}"}}"#))
    }

    /// Calls `send` with typed arguments.
    pub fn send(&mut self, token: &str, args: &SendArgs) -> std::io::Result<RootResponse> {
        let request = serde_json::json!({
            "op": "send",
            "token": token,
            "request_id": args.request_id,
            "recipient": args.recipient,
            "kind": args.kind,
            "mode": args.mode,
            "body": args.body,
        });
        self.raw(&request.to_string())
    }

    /// Calls `status` for the caller's own request id.
    pub fn status(&mut self, token: &str, request_id: &str) -> std::io::Result<RootResponse> {
        let request = serde_json::json!({
            "op": "status",
            "token": token,
            "request_id": request_id,
        });
        self.raw(&request.to_string())
    }
}
